  /// 判断 [date] 是否是法定节假日
  ///
  /// **只看 date 部分** (year/month/day),忽略 hour/minute/second —
  /// 续方提醒用 `DateTime(2026, 2, 17, 8, 30)` 之类具体时间调用时,仍能正确识别。
  ///
  /// 返回 false 不代表是工作日 — 还可能是周末,用 [nextWorkdayAfter] 跳过。
  static bool isHoliday(DateTime date) {
    final key = _dateKey(date);
    return _holidayDates.contains(key);
  }

  /// 返回 [date] 之后第一个工作日
  ///
  /// 跳过:
  /// - 法定节假日 (用 [isHoliday])
  /// - 周末 (周六 / 周日)
  ///
  /// **不处理调休**: 调休让周末上班,但 nextWorkdayAfter 不应跳过"应该上班"的日子
  /// (否则续方会延后),所以这里只看 date 是 holiday + 是 weekend。
  ///
  /// 典型用法:
  /// ```dart
  /// final reminderDate = DateTime(2026, 9, 30); // 国庆前
  /// final nextWorkday = ChineseHolidays.nextWorkdayAfter(reminderDate);
  /// // 跳过 10/1-10/7,返回 10/8
  /// ```
  static DateTime nextWorkdayAfter(DateTime date) {
    DateTime d = date.add(const Duration(days: 1));
    // 安全护栏: 最多跳 30 天,避免死循环 (例如数据缺失 / 异常日期)
    for (int i = 0; i < 30; i++) {
      if (!isHoliday(d) && d.weekday != DateTime.saturday && d.weekday != DateTime.sunday) {
        return d;
      }
      d = d.add(const Duration(days: 1));
    }
    return d;
  }

  /// 内部: 生成 YYYY-MM-DD 字符串
  static String _dateKey(DateTime date) {
    final y = date.year.toString().padLeft(4, '0');
    final m = date.month.toString().padLeft(2, '0');
    final d = date.day.toString().padLeft(2, '0');
    return '$y-$m-$d';
  }
}
